#!/usr/bin/env python3
"""Unified candidate pool - combines results from multiple optimizers.

This module provides utilities to merge, deduplicate, and analyze candidates
generated by multiple optimization algorithms, preparing them for downstream
quality control, clustering, and solution-family discovery.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Sequence

import numpy as np
import pandas as pd

from .api import OptimizationResult, normalize_nucleotide_sequences
from .suite import OptimizerSuiteResult


@dataclass
class CandidatePool:
    """Unified pool of candidates from multiple optimization algorithms.

    Attributes:
        sequences: All unique candidate sequences
        scores: Scalarized objective scores
        activities: Raw model predictions [N, tasks]
        task_names: Names of prediction tasks
        algorithm_sources: Algorithm that produced each candidate
        ranks: Rank within source algorithm
        query_counts: Total queries by source algorithm
        model_query_counts: Actual model calls by source algorithm
        metadata: Additional run information
    """

    sequences: np.ndarray
    scores: np.ndarray
    activities: np.ndarray
    task_names: tuple[str, ...]
    algorithm_sources: np.ndarray
    ranks: np.ndarray
    query_counts: dict[str, int]
    model_query_counts: dict[str, int]
    metadata: dict

    @classmethod
    def from_suite_result(cls, suite: OptimizerSuiteResult) -> "CandidatePool":
        """Create a unified pool from an optimizer suite result.

        This merges candidates from all algorithms, preserving their source
        and performance metadata. Sequences are already unique within each
        algorithm result; cross-algorithm duplicates are preserved to track
        convergence.
        """
        all_sequences = []
        all_scores = []
        all_activities = []
        all_algorithm_sources = []
        all_ranks = []
        task_names = None

        for algorithm, result in suite.results.items():
            n = len(result.sequences)
            all_sequences.extend(result.sequences)
            all_scores.extend(result.scores)

            # Extract activities
            if result.activities is not None:
                all_activities.extend(result.activities)
                if task_names is None:
                    task_names = result.task_names

            # Track source and rank
            all_algorithm_sources.extend([algorithm] * n)
            all_ranks.extend(range(1, n + 1))

        return cls(
            sequences=np.array(all_sequences, dtype=str),
            scores=np.array(all_scores, dtype=np.float64),
            activities=np.array(all_activities, dtype=np.float64) if all_activities else None,
            task_names=task_names or (),
            algorithm_sources=np.array(all_algorithm_sources, dtype=str),
            ranks=np.array(all_ranks, dtype=int),
            query_counts=suite.model_query_counts.copy(),
            model_query_counts=suite.model_query_counts.copy(),
            metadata={
                'initial_count': suite.initial_count,
                'elapsed_seconds': suite.elapsed_seconds.copy(),
            }
        )

    def to_frame(self) -> pd.DataFrame:
        """Convert to a pandas DataFrame for analysis."""
        df = pd.DataFrame({
            'sequence': self.sequences,
            'score': self.scores,
            'algorithm': self.algorithm_sources,
            'rank': self.ranks,
        })

        # Add activities if available
        if self.activities is not None:
            for i, name in enumerate(self.task_names):
                df[f'activity_{name}'] = self.activities[:, i]

        return df

    def deduplicate(self, keep: str = 'best') -> "CandidatePool":
        """Remove duplicate sequences across algorithms.

        Args:
            keep: Strategy for handling duplicates
                - 'best': Keep highest scoring instance
                - 'first': Keep first occurrence (by algorithm order)
                - 'all_sources': Keep all, but annotate as duplicates

        Returns:
            New CandidatePool with duplicates handled according to strategy
        """
        df = self.to_frame()

        if keep == 'best':
            # Keep highest score for each unique sequence
            idx = df.groupby('sequence')['score'].idxmax()
            df_dedup = df.loc[idx].copy()
        elif keep == 'first':
            # Keep first occurrence
            df_dedup = df.drop_duplicates(subset=['sequence'], keep='first').copy()
        elif keep == 'all_sources':
            # Keep all but mark duplicates
            df_dedup = df.copy()
            df_dedup['is_duplicate'] = df_dedup.duplicated(subset=['sequence'], keep='first')
            df_dedup['duplicate_count'] = df.groupby('sequence')['sequence'].transform('count')
        else:
            raise ValueError(f"Invalid keep strategy: {keep}")

        # Reconstruct CandidatePool from deduplicated DataFrame
        activities = None
        if self.activities is not None:
            activity_cols = [f'activity_{name}' for name in self.task_names]
            activities = df_dedup[activity_cols].values

        return CandidatePool(
            sequences=df_dedup['sequence'].values,
            scores=df_dedup['score'].values,
            activities=activities,
            task_names=self.task_names,
            algorithm_sources=df_dedup['algorithm'].values,
            ranks=df_dedup['rank'].values,
            query_counts=self.query_counts,
            model_query_counts=self.model_query_counts,
            metadata=self.metadata,
        )

    def get_convergence_summary(self) -> pd.DataFrame:
        """Analyze sequence convergence across algorithms.

        Returns DataFrame with:
        - sequence: The candidate sequence
        - score: Best score achieved
        - algorithm_count: Number of algorithms that found it
        - algorithms: List of algorithms that found it
        - mean_rank: Average rank across algorithms
        """
        df = self.to_frame()

        convergence = df.groupby('sequence').agg({
            'score': 'max',
            'algorithm': ['count', lambda x: ','.join(sorted(set(x)))],
            'rank': 'mean',
        }).reset_index()

        convergence.columns = [
            'sequence', 'score', 'algorithm_count', 'algorithms', 'mean_rank'
        ]

        return convergence.sort_values('algorithm_count', ascending=False)

    def top_n_by_score(self, n: int = 100) -> "CandidatePool":
        """Return top N candidates by score.

        This selects the best candidates across all algorithms,
        regardless of which algorithm produced them.
        """
        idx = np.argsort(self.scores)[-n:][::-1]

        return CandidatePool(
            sequences=self.sequences[idx],
            scores=self.scores[idx],
            activities=self.activities[idx] if self.activities is not None else None,
            task_names=self.task_names,
            algorithm_sources=self.algorithm_sources[idx],
            ranks=self.ranks[idx],
            query_counts=self.query_counts,
            model_query_counts=self.model_query_counts,
            metadata=self.metadata,
        )

    def __len__(self) -> int:
        return len(self.sequences)

    def __repr__(self) -> str:
        return (
            f"CandidatePool(n={len(self)}, "
            f"algorithms={len(set(self.algorithm_sources))}, "
            f"tasks={len(self.task_names)})"
        )
